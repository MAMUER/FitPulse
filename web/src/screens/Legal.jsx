export default function Legal() {
  const { t, backFromLegal } = useApp();
  const { pathname } = useLocation();

  let kind;
  if (pathname.includes('privacy')) {
    kind = 'privacy';
  } else if (pathname.includes('terms')) {
    kind = 'terms';
  } else {
    kind = 'consent';
  }

  let title;
  if (kind === 'terms') {
    title = t('Пользовательское соглашение', 'Terms of Use');
  } else if (kind === 'consent') {
    title = t(
      'Соглашение об использовании персональных данных',
      'Personal Data Agreement'
    );
  } else {
    title = t('Политика конфиденциальности', 'Privacy Policy');
  }

  let body;
  if (kind === 'terms') {
    body = TERMS;
  } else if (kind === 'consent') {
    body = t(
      'Согласие на обработку персональных данных.',
      'Personal Data Processing Consent.'
    );
  } else {
    body = PRIVACY;
  }

  return (
    <section className='legal'>
      <div className='panel'>
        <div className='panel-head'>
          <div className='panel-title'>{title}</div>
        </div>
        <div className='panel-body'>
          <pre
            style={{ whiteSpace: 'pre-wrap', fontSize: 12, lineHeight: 1.5 }}
          >
            {body}
          </pre>
          <button
            type='button'
            className='secondary full'
            onClick={backFromLegal}
          >
            {t('Назад', 'Back')}
          </button>
        </div>
      </div>
    </section>
  );
}
